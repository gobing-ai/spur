/**
 * Guard: the published `@gobing-ai/spur/board` declaration is GENERATED from the authoring source
 * (`apps/web/src/modules/contribution.ts`) and cannot drift from it (task 0988 R1; moved to the app
 * layer by A94 1410).
 *
 * One authoring source, a declaration-only artifact, no React value import anywhere in the CLI
 * surface.
 */
import { describe, expect, test } from 'bun:test';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import {
    BOARD_DECLARATION_REQUIRED_LINES,
    boardAuthoringSource,
    boardDeclarationTarget,
    KIT_COMPONENT_DECLARATIONS,
    KIT_DECLARATION_REQUIRED_LINES,
    kitDeclarationEntry,
    kitDeclarationRoot,
    renderBoardDeclaration,
    renderKitDeclarations,
} from '../../src/builder/emit-board-types';

/** Repo root: packages/app/tests/builder → repo. */
const SOURCE_ROOT = join(import.meta.dir, '../../../..');

describe('emit-board-types', () => {
    test('the committed artifact is exactly what the authoring source generates', async () => {
        const onDisk = await readFile(boardDeclarationTarget(SOURCE_ROOT), 'utf-8');
        expect(onDisk).toBe(renderBoardDeclaration(SOURCE_ROOT));
    });

    test('the artifact states the frozen ABI and the entry export name', () => {
        const declaration = renderBoardDeclaration(SOURCE_ROOT);
        for (const line of BOARD_DECLARATION_REQUIRED_LINES) expect(declaration).toContain(line);
        expect(declaration).toContain('export declare const webModule: BoardModuleContribution;');
        expect(declaration.split('\n')[0]).toBe('// Generated by scripts/commands/emit-board-types.ts from');
        expect(declaration).toContain('apps/web/src/modules/contribution.ts');
        expect(boardAuthoringSource(SOURCE_ROOT).endsWith('apps/web/src/modules/contribution.ts')).toBeTrue();
    });

    test('the artifact is declaration-only: no runtime React import, no require', () => {
        const declaration = renderBoardDeclaration(SOURCE_ROOT);
        expect(declaration).toContain("import type { ComponentType } from 'react';");
        expect(/^\s*import\s+(?!type\b)/m.test(declaration)).toBeFalse();
        expect(declaration).not.toContain('require(');
        // No implementation body leaks in: only declarations are emitted.
        expect(/\bfunction\s+\w+\s*\(/.test(declaration)).toBeFalse();
    });

    test('regeneration is deterministic', () => {
        expect(renderBoardDeclaration(SOURCE_ROOT)).toBe(renderBoardDeclaration(SOURCE_ROOT));
    });
});

describe('emit-board-types — the module-kit declarations (A81 1349 R3)', () => {
    test('the committed mirror is exactly what the kit source generates', async () => {
        const declarations = renderKitDeclarations(SOURCE_ROOT);
        for (const [relativePath, text] of declarations) {
            const onDisk = await readFile(join(kitDeclarationRoot(SOURCE_ROOT), relativePath), 'utf-8');
            expect([relativePath, onDisk]).toEqual([relativePath, text]);
        }
        // The published entry lives in the mirror, and the mirror holds only kit paths.
        expect(kitDeclarationEntry(SOURCE_ROOT)).toBe(join(kitDeclarationRoot(SOURCE_ROOT), 'module-kit/index.d.ts'));
        expect(declarations.has('module-kit/index.d.ts')).toBe(true);
    });

    test('the entry re-exports every kit name, and each component declares itself', () => {
        const declarations = renderKitDeclarations(SOURCE_ROOT);
        const entry = declarations.get('module-kit/index.d.ts');
        if (entry === undefined) throw new Error('the kit entry declaration is missing');
        for (const line of KIT_DECLARATION_REQUIRED_LINES) expect(entry).toContain(line);
        expect(entry.split('\n')[0]).toBe('// Generated by scripts/commands/emit-board-types.ts from');
        for (const [relativePath, declaration] of Object.entries(KIT_COMPONENT_DECLARATIONS)) {
            expect(declarations.get(relativePath), `${relativePath} is missing`).toContain(declaration);
        }
    });

    test('the kit declarations are declaration-only — no React value import reaches the CLI package', () => {
        for (const [relativePath, text] of renderKitDeclarations(SOURCE_ROOT)) {
            expect([relativePath, /^\s*import\s+(?!type\b)/m.test(text)]).toEqual([relativePath, false]);
            expect([relativePath, text.includes('require(')]).toEqual([relativePath, false]);
        }
    });

    test('regeneration is deterministic', () => {
        expect([...renderKitDeclarations(SOURCE_ROOT)]).toEqual([...renderKitDeclarations(SOURCE_ROOT)]);
    });
});
