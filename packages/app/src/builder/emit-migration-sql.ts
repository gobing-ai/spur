/**
 * Emit `packages/domain/src/migration-sql.generated.ts` from the released 0037 SQL (task 1312).
 *
 * The offline CLI bundle cannot read `drizzle/` at runtime, so migration SQL is embedded as a string.
 * This pilot makes the released `.sql` file the single authoring source for one mirror (0037, chosen
 * by the 1311 ownership evidence) instead of a handwritten twin. Released `.sql` bytes never change.
 *
 * A94 1410: the checkout is an explicit source root, so `spur builder emit-migration-sql` runs the
 * same generator downstream. The generated banner keeps its original script path on purpose — the
 * move's byte-equivalence proof (A94 R3) is `git diff --exit-code` on the artifact.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import type { BuildResult } from './compile';

/** Authoring source for the embedded migration SQL. */
export function migrationSqlSource(sourceRoot: string): string {
    return join(sourceRoot, 'drizzle/0037_spur_cli_history_dimension_marts.sql');
}

/** Generated module inside the domain package. */
export function migrationSqlTarget(sourceRoot: string): string {
    return join(sourceRoot, 'packages/domain/src/migration-sql.generated.ts');
}

/** Module text for the given SQL: a template literal with `\`, backtick and `${` escaped. */
export function renderMigrationSqlModule(sql: string): string {
    const literal = sql.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
    return (
        '// Generated by scripts/commands/emit-migration-sql.ts from\n' +
        '// drizzle/0037_spur_cli_history_dimension_marts.sql — edit nothing here; the .sql is released history.\n' +
        '/** Migration 0037: dimension marts (task 0743); verbatim released SQL. */\n' +
        `export const HISTORY_DIMENSION_MARTS_SCHEMA_SQL = \`${literal}\`;\n`
    );
}

/** Emission options: the checkout plus an optional explicit target module. */
export interface EmitMigrationSqlOptions {
    sourceRoot: string;
    /** default `<sourceRoot>/packages/domain/src/migration-sql.generated.ts` */
    target?: string;
}

/** Write the module, reporting whether the file changed on disk. */
export async function emitMigrationSql(options: EmitMigrationSqlOptions): Promise<BuildResult> {
    const target = options.target ?? migrationSqlTarget(options.sourceRoot);
    const text = renderMigrationSqlModule(await readFile(migrationSqlSource(options.sourceRoot), 'utf-8'));
    const existing = await readFile(target, 'utf-8').catch(() => undefined);
    const changed = existing !== text;
    if (changed) {
        await mkdir(dirname(target), { recursive: true });
        await writeFile(target, text, 'utf-8');
    }
    return {
        ok: true,
        sourceRoot: options.sourceRoot,
        artifacts: [{ path: target, kind: `migration-sql:${changed ? 'changed' : 'unchanged'}` }],
        diagnostics: [],
    };
}
