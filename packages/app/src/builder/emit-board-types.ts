/**
 * Emit the declaration-only `@gobing-ai/spur/board` artifact (task 0988 R1).
 *
 * `apps/web/src/modules/contribution.ts` is the single authoring source: the CLI package
 * must not import React, must not re-declare the ABI by hand, and must not ship a runtime
 * module for `./board`. This service runs the TypeScript compiler in
 * `emitDeclarationOnly` mode over that one source file and writes the resulting `.d.ts`
 * to `apps/cli/board/index.d.ts`, which `apps/cli/package.json` exposes as `./board`.
 *
 * A94 1410: every root is an explicit source root, so the same service runs as
 * `spur builder emit-board-types` outside this repository. The generated banner keeps its original
 * script path on purpose — rewriting it would change bytes the release tarball already ships, and
 * the byte-equivalence proof for the move (A94 R3) is `git diff --exit-code` on the artifacts.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import ts from 'typescript';
import type { BuildArtifact, BuildResult } from './compile';

/** Declared shape the generated artifact must contain (frozen output, task 0988). */
export const BOARD_DECLARATION_REQUIRED_LINES: readonly string[] = [
    'export interface BoardModuleContribution {',
    'readonly apiVersion: 1;',
    'readonly component: ComponentType;',
    'readonly rightPanelComponent?: ComponentType;',
    'export declare const webModule: BoardModuleContribution;',
];

const HEADER =
    '// Generated by scripts/commands/emit-board-types.ts from\n' +
    '// apps/web/src/modules/contribution.ts — edit the authoring source, then regenerate.\n';

/** The single authoring source for the public contribution ABI. */
export function boardAuthoringSource(sourceRoot: string): string {
    return join(sourceRoot, 'apps/web/src/modules/contribution.ts');
}

/** The module-kit barrel — the authoring source for the `@gobing-ai/spur/board/ui` export. */
export function kitAuthoringSource(sourceRoot: string): string {
    return join(sourceRoot, 'apps/web/src/components/module-kit/index.ts');
}

/** Mirror root of the kit declarations: relative imports keep resolving after the mirror. */
export function kitSourceRoot(sourceRoot: string): string {
    return join(sourceRoot, 'apps/web/src/components');
}

/** Path of the generated artifact inside the published CLI package. */
export function boardDeclarationTarget(sourceRoot: string): string {
    return join(sourceRoot, 'apps/cli/board/index.d.ts');
}

/** Directory the kit declarations are mirrored into inside the published CLI package. */
export function kitDeclarationRoot(sourceRoot: string): string {
    return join(sourceRoot, 'apps/cli/board/kit');
}

/** Kit entry inside that mirror — what `apps/cli/package.json` maps `./board/ui` to. */
export function kitDeclarationEntry(sourceRoot: string): string {
    return join(kitDeclarationRoot(sourceRoot), 'module-kit/index.d.ts');
}

/**
 * Declared shape the generated kit entry must contain (frozen output, task A81 1349).
 *
 * The entry is a barrel, so it re-exports names rather than declaring them; each component's own
 * declaration is pinned by {@link KIT_COMPONENT_DECLARATIONS} below.
 */
export const KIT_DECLARATION_REQUIRED_LINES: readonly string[] = [
    'export { Diagnostic',
    'export { EmptyState',
    'export { ModuleHeader',
    'export { ModuleShell',
    'export { type ModuleTab, ModuleTabs',
    'export { TimeRangePresets',
    'export { Loading',
    'export { Card, CardBody',
    'export { Badge',
    'export { Button',
];

/** One generated declaration file per shell primitive: file -> the `declare function` it must hold. */
export const KIT_COMPONENT_DECLARATIONS: Readonly<Record<string, string>> = {
    'module-kit/ModuleShell.d.ts': 'export declare function ModuleShell',
    'module-kit/ModuleHeader.d.ts': 'export declare function ModuleHeader',
    'module-kit/ModuleTabs.d.ts': 'export declare function ModuleTabs',
    'module-kit/TimeRangePresets.d.ts': 'export declare function TimeRangePresets',
    'module-kit/EmptyState.d.ts': 'export declare function EmptyState',
    'module-kit/Diagnostic.d.ts': 'export declare function Diagnostic',
};

/** Board declaration options: the checkout plus an optional explicit target. */
export interface EmitBoardTypesOptions {
    sourceRoot: string;
    /** default `<sourceRoot>/apps/cli/board/index.d.ts` */
    target?: string;
}

/** Kit declaration options: the checkout plus an optional explicit mirror root. */
export interface EmitKitTypesOptions {
    sourceRoot: string;
    /** default `<sourceRoot>/apps/cli/board/kit` */
    root?: string;
}

/**
 * Declaration text for the authoring source — deterministic and compiler-derived.
 * Fails loudly if the compiler did not produce exactly one declaration file.
 */
export function renderBoardDeclaration(sourceRoot: string): string {
    const authoringSource = boardAuthoringSource(sourceRoot);
    const program = ts.createProgram({ rootNames: [authoringSource], options: declarationOptions() });
    const source = program.getSourceFile(authoringSource);
    if (!source) throw new Error(`emit-board-types: cannot load ${authoringSource}`);

    const emitted = new Map<string, string>();
    const diagnostics = program.getSemanticDiagnostics(source);
    if (diagnostics.length > 0) {
        throw new Error(
            `emit-board-types: ${authoringSource} does not compile:\n${ts.formatDiagnosticsWithColorAndContext(diagnostics, hostFor(source))}`,
        );
    }
    program.emit(source, (fileName, text) => void emitted.set(fileName, text), undefined, true);

    if (emitted.size !== 1) {
        throw new Error(`emit-board-types: expected exactly one declaration file, got ${emitted.size}`);
    }
    const declaration = [...emitted.values()][0] as string;
    const body = `${HEADER}${declaration.trimEnd()}\n`;

    for (const line of BOARD_DECLARATION_REQUIRED_LINES) {
        if (!body.includes(line)) {
            throw new Error(
                `emit-board-types: the frozen contribution ABI line "${line}" is missing from the generated artifact`,
            );
        }
    }
    if (/^\s*import\s+(?!type\b)/m.test(body) || body.includes('require(')) {
        throw new Error('emit-board-types: the artifact must not contain a React value import');
    }
    return body;
}

/** Compiler options for a declaration-only emit (no project tsconfig is loaded here). */
function declarationOptions(): ts.CompilerOptions {
    return {
        declaration: true,
        emitDeclarationOnly: true,
        target: ts.ScriptTarget.ESNext,
        module: ts.ModuleKind.ESNext,
        moduleResolution: ts.ModuleResolutionKind.Bundler,
        jsx: ts.JsxEmit.ReactJSX,
        lib: ['lib.esnext.d.ts', 'lib.dom.d.ts', 'lib.dom.iterable.d.ts'],
        strict: true,
        skipLibCheck: true,
        types: [],
    };
}

/** Kit declarations: path relative to {@link kitSourceRoot} -> declaration text. */
export function renderKitDeclarations(sourceRoot: string): Map<string, string> {
    const authoringSource = kitAuthoringSource(sourceRoot);
    const sourceRootComponents = kitSourceRoot(sourceRoot);
    const program = ts.createProgram({ rootNames: [authoringSource], options: declarationOptions() });
    const source = program.getSourceFile(authoringSource);
    if (!source) throw new Error(`emit-board-types: cannot load ${authoringSource}`);
    const diagnostics = program.getSemanticDiagnostics(source);
    if (diagnostics.length > 0) {
        throw new Error(
            `emit-board-types: ${authoringSource} does not compile:\n${ts.formatDiagnosticsWithColorAndContext(diagnostics, hostFor(source))}`,
        );
    }

    const files = new Map<string, string>();
    program.emit(undefined, (fileName, text) => void files.set(fileName, text), undefined, true);
    for (const fileName of files.keys()) {
        if (!fileName.startsWith(`${sourceRootComponents}/`)) {
            throw new Error(
                `emit-board-types: declaration "${fileName}" falls outside ${sourceRootComponents}, so the mirror's relative imports would break`,
            );
        }
    }

    const declarations = new Map<string, string>();
    for (const [fileName, text] of files) {
        const relativePath = fileName.slice(sourceRootComponents.length + 1);
        // A primitive that uses `React.isValidElement` emits `import React from 'react'` even in a
        // declaration. In a `.d.ts` that import is erased either way; marking it `import type` keeps
        // the published artifact honest about carrying no runtime React import.
        const body = text
            .split('\n')
            .map((line) => (line === "import React from 'react';" ? "import type React from 'react';" : line))
            .join('\n')
            .replace(/^\uFEFF/, '')
            .trimEnd();
        declarations.set(relativePath, relativePath === 'module-kit/index.d.ts' ? `${HEADER}${body}\n` : `${body}\n`);
        if (relativePath === 'module-kit/index.d.ts') {
            for (const line of KIT_DECLARATION_REQUIRED_LINES) {
                if (!body.includes(line)) {
                    throw new Error(
                        `emit-board-types: the frozen kit declaration line "${line}" is missing from the generated entry`,
                    );
                }
            }
            if (/^\s*import\s+(?!type\b)/m.test(body) || body.includes('require(')) {
                throw new Error('emit-board-types: the kit declaration must not contain a React value import');
            }
        }
    }
    for (const [relativePath, declaration] of Object.entries(KIT_COMPONENT_DECLARATIONS)) {
        const body = declarations.get(relativePath);
        if (body === undefined || !body.includes(declaration)) {
            throw new Error(
                `emit-board-types: ${relativePath} must declare "${declaration}" — the kit's public props are its contract`,
            );
        }
    }
    return declarations;
}

/** Write the kit declaration mirror. */
export async function emitKitDeclarations(options: EmitKitTypesOptions): Promise<BuildResult> {
    const root = options.root ?? kitDeclarationRoot(options.sourceRoot);
    const declarations = renderKitDeclarations(options.sourceRoot);
    let changed = false;
    for (const [relativePath, text] of declarations) {
        const target = join(root, relativePath);
        const existing = await readFile(target, 'utf-8').catch(() => undefined);
        if (existing === text) continue;
        await mkdir(dirname(target), { recursive: true });
        await writeFile(target, text, 'utf-8');
        changed = true;
    }
    return {
        ok: true,
        sourceRoot: options.sourceRoot,
        artifacts: [
            {
                path: join(root, 'module-kit/index.d.ts'),
                kind: `kit:${declarations.size} files:${changed ? 'changed' : 'unchanged'}`,
            },
        ],
        diagnostics: [],
    };
}

/** Write the board declaration artifact. */
export async function emitBoardDeclarations(options: EmitBoardTypesOptions): Promise<BuildResult> {
    const target = options.target ?? boardDeclarationTarget(options.sourceRoot);
    const text = renderBoardDeclaration(options.sourceRoot);
    const existing = await readFile(target, 'utf-8').catch(() => undefined);
    const changed = existing !== text;
    if (changed) {
        await mkdir(dirname(target), { recursive: true });
        await writeFile(target, text, 'utf-8');
    }
    const artifacts: BuildArtifact[] = [{ path: target, kind: `board:${changed ? 'changed' : 'unchanged'}` }];
    return { ok: true, sourceRoot: options.sourceRoot, artifacts, diagnostics: [] };
}

/** Formatting host for compiler diagnostics (no project tsconfig is loaded here). */
function hostFor(source: ts.SourceFile): ts.FormatDiagnosticsHost {
    return {
        getCanonicalFileName: (f) => f,
        getCurrentDirectory: () => dirname(source.fileName),
        getNewLine: () => '\n',
    };
}
