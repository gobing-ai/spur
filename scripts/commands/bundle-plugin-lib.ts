/**
 * Generate the plugin-side lib bundles for thin plugin scripts (ADR-130 lib rule, task 1005).
 *
 * `packages/app` owns the workflow/history logic cores, but the plugin scripts
 * `plugins/sp/scripts/workflow-step-profile.ts` and `history-anatomy-cache.ts` are ADR-065
 * standard scripts: their committed `.mjs` twins must run under bare `node` with no monorepo
 * dependency, and `superskill script convert` cannot bundle workspace imports. The bridge is a
 * **generated** ESM bundle under `plugins/sp/lib/`, committed, imported and re-exported by the
 * script through a relative path.
 *
 * Outputs (gitignored from Biome, all committed):
 *   plugins/sp/lib/step-profile.generated.mjs|.d.mts     — step-profile core (task 1005 R1)
 *   plugins/sp/lib/history-anatomy.generated.mjs|.d.mts  — history-anatomy cache core (task 1005 R2)
 *   plugins/sp/lib/idea-handoff.generated.mjs|.d.mts     — minified CLI wrapper (task 0824)
 *   plugins/sp/lib/inline-run.generated.mjs|.d.mts       — inline driver surface (task 0972)
 *   plugins/sp/lib/residual-scan.generated.mjs|.d.mts    — residual-scan core (task 1003 R5)
 *   plugins/sp/lib/quality-gate.generated.mjs|.d.mts     — quality-gate core (task 1006 R1)
 *
 * `bundleIdeaHandoffLib` (task 0824) minifies with `import.meta.main` pinned to `false`; the
 * unminified lib bundles stay byte-deterministic via `normalizeBundleComments` (task 1003 R5
 * gate). Run via `bun run build:plugin-lib`; chained ahead of `build:scripts`.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url));

/**
 * Bun.build emits entrypoint comments relative to process.cwd(), so the committed bytes of an
 * unminified lib differed between a root-cwd generation (`// packages/...`) and a
 * scripts-workspace regeneration (`// ../packages/...`). Pin to repo-relative for
 * cwd-independent determinism (task 1003 R5 gate).
 */
function normalizeBundleComments(mjsPath: string): void {
    const raw = readFileSync(mjsPath, 'utf8');
    const normalized = raw.replace(/^\/\/ (?:\.\.\/)+/gm, '// ');
    if (normalized !== raw) writeFileSync(mjsPath, normalized);
}

