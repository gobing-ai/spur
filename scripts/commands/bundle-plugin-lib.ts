/**
 * Bundle the step-profile aggregation core (task 1005 R1) into a standalone node-runnable ESM
 * module. Unminified — the source is pure (node builtins only), so determinism holds. The plugin
 * script `plugins/sp/scripts/workflow-step-profile.ts` keeps the IO glue and re-exports this.
 */
export async function bundleStepProfileLib(outDir: string = OUT_DIR): Promise<{ mjs: string; dmts: string }> {
    const result = await Bun.build({
        entrypoints: [join(REPO_ROOT, 'packages/app/src/workflow/step-profile.ts')],
        target: 'node',
        format: 'esm',
        minify: false,
        root: join(REPO_ROOT, 'packages/app/src/workflow'),
        naming: 'step-profile.generated.mjs',
        outdir: outDir,
    });
    if (!result.success) {
        throw new Error(`step-profile bundle failed: ${result.logs.map((l) => String(l)).join('\n')}`);
    }
    const mjs = join(outDir, 'step-profile.generated.mjs');
    const dmts = join(outDir, 'step-profile.generated.d.mts');
    mkdirSync(outDir, { recursive: true });
    writeFileSync(dmts, STEP_PROFILE_DECLS);
    normalizeBundleComments(mjs);
    return { mjs, dmts };
}

