/**
 * integrations-e2e — prove the A82 protocol fixes against a REAL `spur self serve` (feature A82,
 * task 1425 R1–R3; design `integrations-module.md` §4).
 *
 * Usage: bun scripts/spur-dev.ts integrations-e2e [--keep]
 *
 * One scratch project is scaffolded under `$TMPDIR` with a declared fleet member whose agent is a
 * stub binary on a controlled PATH (the fleet-e2e model): the stub sleeps for a minute, so a cold
 * drain spawns a REAL child the CancelTask can abort — the only way to prove `runStopped: true`
 * rather than a seeded row that has no process behind it.
 *
 * Every step records its command, the HTTP status or exit code, the assertion it proves and its
 * evidence. The run writes `docs/reports/integrations-e2e-receipt.json` (stable name, overwritten
 * each run) and exits nonzero if any assertion failed.
 *
 * Determinism: no wall-clock assertions and no ports, temp paths or ids in the asserted projection
 * (`steps[].{step,requirement,status,expected}`) — two consecutive runs must agree on it. The
 * receipt's `context` block carries the volatile values (port, scratch path, timestamps).
 *
 * The Board leg is a separate workspace test (`apps/web/tests/modules/integrations-browser.heavy.test.ts`):
 * the CDP harness lives in `apps/web/tests`, and a script under `scripts/` must not import it.
 */

import { chmodSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:net';
import { tmpdir } from 'node:os';
import { join, relative, resolve } from 'node:path';
import { getEnvVar, getEnvVars } from '@gobing-ai/spur-config';
import { type Subprocess, spawn } from 'bun';

const REPO_ROOT = resolve(import.meta.dir, '../..');
const CLI = join(REPO_ROOT, 'apps/cli/src/index.ts');
const RECEIPT = join(REPO_ROOT, 'docs/reports/integrations-e2e-receipt.json');
const ARTIFACT = 'integrations-e2e';
const MEMBER_LOCAL = 'coder';
const AGENT_TYPE = 'claude';
const EXECUTOR = 'stub-lane';
const MCP_TOKEN = 'integrations-e2e-mcp-token';
const A2A_TOKEN = 'integrations-e2e-a2a-token';
const MCP_AUTH_ENV = 'SPUR_MCP_TOKEN';
const A2A_AUTH_ENV = 'SPUR_A2A_TOKEN';
/** The stub sleeps this long, so a cancel always has a live child to abort. */
const STUB_SLEEP_SECONDS = 60;

type StepStatus = 'passed' | 'failed' | 'skipped';

/** One receipt row: what was run, what it had to prove, and what it observed. */
interface StepRow {
    step: string;
    requirement: string;
    command: string;
    httpStatus: number | null;
    exitCode: number | null;
    status: StepStatus;
    expected: string;
    evidence: string;
}

/** A free TCP port, so two runs never collide. */
async function freePort(): Promise<number> {
    return new Promise((resolvePort, reject) => {
        const server = createServer();
        server.on('error', reject);
        server.listen(0, '127.0.0.1', () => {
            const address = server.address();
            const port = typeof address === 'object' && address !== null ? address.port : 0;
            server.close(() => resolvePort(port));
        });
    });
}

/** Bounded poll: resolves with the first truthy probe result, or undefined at the deadline. */
async function pollUntil<T>(probe: () => Promise<T | undefined>, budgetMs: number): Promise<T | undefined> {
    const deadline = Date.now() + budgetMs;
    while (Date.now() < deadline) {
        const value = await probe();
        if (value !== undefined) return value;
        await Bun.sleep(200);
    }
    return undefined;
}

/** The stub model: answers the preflight probes, then sleeps so its child outlives a cancel. */
function stubSource(): string {
    return `#!/usr/bin/env bun
// Generated by scripts/commands/integrations-e2e.ts — a model that never thinks, only sleeps.
const argv = process.argv.slice(2);
if (argv.includes('--version')) {
    console.log('claude-code 2.0.1 (integrations-e2e-stub)');
    process.exit(0);
}
if (argv.includes('--help')) {
    console.log('integrations-e2e-stub');
    process.exit(0);
}
await Bun.sleep(${STUB_SLEEP_SECONDS} * 1000);
process.exit(0);
`;
}

/** The scratch project: one declared member, planning folders, nothing autostarted. */
function scaffold(dir: string): string {
    mkdirSync(join(dir, '.spur'), { recursive: true });
    mkdirSync(join(dir, 'docs/tasks'), { recursive: true });
    mkdirSync(join(dir, 'docs/features'), { recursive: true });
    writeFileSync(
        join(dir, '.spur/config.yaml'),
        [
            'version: "1.2"',
            'name: integrations-e2e',
            'agent:',
            '  executors:',
            `    - name: ${EXECUTOR}`,
            `      agent: ${AGENT_TYPE}`,
            '      tier: standard',
            '      executionCapabilities:',
            '        version: 1',
            '        axes:',
            '          fsRead:',
            '            state: available',
            '            provenance: native-known',
            '          fsWrite:',
            '            state: available',
            '            provenance: native-known',
            '          processSpawn:',
            '            state: available',
            '            provenance: native-known',
            '  fleet:',
            '    strategy: rest',
            '    members:',
            `      - id: ${MEMBER_LOCAL}`,
            `        executor: ${EXECUTOR}`,
            '',
        ].join('\n'),
    );
    // The controlled PATH: the stub model first, then a `bun` shim so the stub's shebang resolves
    // without an agent installed on the operator's machine.
    const binDir = join(dir, 'bin');
    mkdirSync(binDir, { recursive: true });
    writeFileSync(join(binDir, AGENT_TYPE), stubSource());
    chmodSync(join(binDir, AGENT_TYPE), 0o755);
    writeFileSync(join(binDir, 'bun'), `#!/bin/sh\nexec ${process.execPath} "$@"\n`);
    chmodSync(join(binDir, 'bun'), 0o755);
    return binDir;
}

/** `spur self serve` for the scratch project, with both protocol surfaces on. */
function startServe(dir: string, port: number): Subprocess<'ignore', 'pipe', 'pipe'> {
    return spawn({
        cmd: ['bun', CLI, 'self', 'serve', '--port', String(port), '--host', '127.0.0.1', '--no-open'],
        cwd: dir,
        stdout: 'pipe',
        stderr: 'pipe',
        env: {
            ...getEnvVars(),
            // Throwaway roots must never touch the operator's real project registry.
            SPUR_PROJECTS_FILE: join(dir, 'projects.json'),
            SPUR_SLASH_COMMANDS_FILE: join(dir, 'slash_commands.json'),
            SPUR_MCP_ENABLED: '1',
            SPUR_MCP_AUTH_ENV: MCP_AUTH_ENV,
            [MCP_AUTH_ENV]: MCP_TOKEN,
            SPUR_A2A_ENABLED: '1',
            SPUR_A2A_AUTH_ENV: A2A_AUTH_ENV,
            [A2A_AUTH_ENV]: A2A_TOKEN,
        },
    });
}

/** The member loop that drains A2A requests (the same command `spur agent loop` runs). */
function startMemberLoop(dir: string, binDir: string, specId: string) {
    const logDir = join(dir, '.spur/logs');
    mkdirSync(logDir, { recursive: true });
    return spawn({
        cmd: [process.execPath, 'run', CLI, 'agent', 'loop', '--spec', specId, '--poll', '1000'],
        cwd: dir,
        stdin: 'ignore',
        stdout: Bun.file(join(logDir, 'member-loop.out.log')),
        stderr: Bun.file(join(logDir, 'member-loop.err.log')),
        env: {
            ...getEnvVars(),
            PATH: `${binDir}:${getEnvVar('PATH') ?? ''}`,
        },
    });
}

/** POST one JSON-RPC body to the MCP endpoint. */
async function mcp(root: string, body: unknown): Promise<{ status: number; json: unknown }> {
    const res = await fetch(`${root}/mcp`, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'Mcp-Protocol-Version': '2026-07-28',
            Authorization: `Bearer ${MCP_TOKEN}`,
        },
        body: JSON.stringify(body),
    });
    return { status: res.status, json: await res.json().catch(() => null) };
}

/** The newest ledger row for one event name (the observable surface the Board reads). */
async function newestEvent(root: string, name: string): Promise<Record<string, unknown> | null> {
    const res = await fetch(`${root}/api/events/history?names=${encodeURIComponent(name)}&limit=5`);
    if (!res.ok) return null;
    const body = (await res.json()) as { events?: Array<{ payload?: { data?: unknown } }> };
    const data = body.events?.[0]?.payload?.data;
    return typeof data === 'object' && data !== null ? (data as Record<string, unknown>) : null;
}

function record(
    rows: StepRow[],
    row: Omit<StepRow, 'status' | 'evidence'> & { passed: boolean; evidence: string },
): void {
    rows.push({
        step: row.step,
        requirement: row.requirement,
        command: row.command,
        httpStatus: row.httpStatus,
        exitCode: row.exitCode,
        status: row.passed ? 'passed' : 'failed',
        expected: row.expected,
        evidence: row.evidence.replaceAll(MCP_TOKEN, '[REDACTED]').replaceAll(A2A_TOKEN, '[REDACTED]').slice(0, 2000),
    });
}

/** Drive the whole protocol leg and write the receipt. Returns the process exit code. */
export async function runIntegrationsE2e(args: string[] = []): Promise<number> {
    const keep = args.includes('--keep');
    const scratch = mkdtempSync(join(tmpdir(), 'spur-integrations-e2e-'));
    const binDir = scaffold(scratch);
    const port = await freePort();
    const root = `http://127.0.0.1:${port}`;
    const member = `${scratch.split('/').pop() ?? 'scratch'}-${MEMBER_LOCAL}`;
    const cardPath = `${root}/a2a/members/${member}/.well-known/agent-card.json`;
    const rows: StepRow[] = [];
    let serve: Subprocess<'ignore', 'pipe', 'pipe'> | undefined;
    let loop: ReturnType<typeof startMemberLoop> | undefined;

    try {
        serve = startServe(scratch, port);
        const healthy = await pollUntil(async () => {
            try {
                const res = await fetch(`${root}/api/health`);
                return res.ok ? true : undefined;
            } catch {
                return undefined;
            }
        }, 45_000);
        record(rows, {
            step: 'serve-ready',
            requirement: 'R1',
            command: 'spur self serve (MCP + A2A enabled)',
            httpStatus: healthy === true ? 200 : null,
            exitCode: null,
            passed: healthy === true,
            expected: '/api/health answers 200',
            evidence: healthy === true ? 'health ok' : 'server never answered /api/health',
        });
        if (healthy !== true) throw new Error('spur self serve never became healthy');

        // ── R2 / F1 — an argument-validation failure is `invalid_arguments` ──────────────
        const badCall = await mcp(root, {
            jsonrpc: '2.0',
            id: 1,
            method: 'tools/call',
            params: { name: 'sp_task_update', arguments: { wbs: '0001', bogus: 'x' } },
        });
        const failedEvent = await newestEvent(root, 'mcp.tool.failed');
        const errorCode = failedEvent?.errorCode;
        record(rows, {
            step: 'mcp-invalid-arguments',
            requirement: 'R2 / F1',
            command: 'POST /mcp tools/call sp_task_update {bogus}',
            httpStatus: badCall.status,
            exitCode: null,
            passed: badCall.status === 500 && errorCode === 'invalid_arguments',
            expected: 'http 500 and mcp.tool.failed errorCode=invalid_arguments',
            evidence: `http ${badCall.status} errorCode=${String(errorCode)}`,
        });

        // ── R2 / F2 — every advertised tool carries annotations ──────────────────────────
        const listed = await mcp(root, { jsonrpc: '2.0', id: 2, method: 'tools/list' });
        const tools = ((listed.json as { result?: { tools?: Array<{ name: string; annotations?: unknown }> } })?.result
            ?.tools ?? []) as Array<{ name: string; annotations?: { readOnlyHint?: boolean } }>;
        const annotated = tools.filter((tool) => typeof tool.annotations?.readOnlyHint === 'boolean');
        const readTools = tools.filter((tool) => tool.annotations?.readOnlyHint === true).map((tool) => tool.name);
        record(rows, {
            step: 'mcp-annotations',
            requirement: 'R2 / F2',
            command: 'POST /mcp tools/list',
            httpStatus: listed.status,
            exitCode: null,
            passed: tools.length > 0 && annotated.length === tools.length && readTools.length > 0,
            expected: 'every tool declares readOnlyHint, and at least one is a read',
            evidence: `${tools.length} tools, ${annotated.length} annotated, reads=${readTools.sort().join(',')}`,
        });

        // ── R2 / F3, F4 — the card is public and carries skills ─────────────────────────
        const cardRes = await fetch(cardPath);
        const card = (await cardRes.json().catch(() => null)) as {
            skills?: Array<{ id?: string }>;
            supportedInterfaces?: Array<{ protocolVersion?: string }>;
        } | null;
        const skillIds = (card?.skills ?? []).map((skill) => skill.id ?? '');
        record(rows, {
            step: 'a2a-card-public',
            requirement: 'R2 / F3, F4',
            command: `GET ${cardPath} (no bearer token)`,
            httpStatus: cardRes.status,
            exitCode: null,
            passed: cardRes.status === 200 && skillIds.length > 0,
            expected: 'http 200 with a non-empty skills array',
            evidence: `http ${cardRes.status} skills=${skillIds.join(',')} protocol=${String(
                card?.supportedInterfaces?.[0]?.protocolVersion,
            )}`,
        });

        const deniedSend = await fetch(`${root}/a2a/members/${member}/message:send`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ message: { messageId: 'm-denied', role: 'ROLE_USER', parts: [{ text: 'hi' }] } }),
        });
        const deniedEvent = await newestEvent(root, 'auth.denied');
        record(rows, {
            step: 'a2a-send-refused',
            requirement: 'R2 / F3',
            command: `POST /a2a/members/<member>/message:send (no bearer token)`,
            httpStatus: deniedSend.status,
            exitCode: null,
            passed: deniedSend.status === 401 && deniedEvent?.surface === 'a2a',
            expected: 'http 401 and an auth.denied event for surface a2a',
            evidence: `http ${deniedSend.status} auth.denied surface=${String(deniedEvent?.surface)}`,
        });

        // ── R2 / F6 — cancel stops the run, not the member ───────────────────────────────
        loop = startMemberLoop(scratch, binDir, member);
        const send = async (messageId: string) =>
            fetch(`${root}/a2a/members/${member}/message:send`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${A2A_TOKEN}` },
                body: JSON.stringify({
                    message: { messageId, role: 'ROLE_USER', parts: [{ text: 'run the sleeping turn' }] },
                }),
            });
        const first = await send('m-cancel');
        const firstBody = (await first.json().catch(() => null)) as { task?: { id?: string } } | null;
        const taskId = firstBody?.task?.id ?? '';
        const sendCancel = () =>
            fetch(`${root}/a2a/members/${member}/tasks/${taskId}:cancel`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${A2A_TOKEN}` },
                body: '{}',
            });
        // Cancel is accepted only while the task's run row is live (1422 R1), and the task can
        // already project WORKING from `claimed` alone — so the accepted cancel IS the barrier:
        // poll `:cancel` until it stops answering FAILED_PRECONDITION, within the drain's budget.
        const cancelUntilAccepted = async (): Promise<Response> => {
            const deadline = Date.now() + 60_000;
            let last = await sendCancel();
            while (last.status === 400 && Date.now() < deadline) {
                await Bun.sleep(250);
                last = await sendCancel();
            }
            return last;
        };
        const cancelRes = await cancelUntilAccepted();
        const working = cancelRes.status === 200;
        const cancelText = await cancelRes.text().catch(() => '');
        const cancelBody = JSON.parse(cancelText === '' ? '{}' : cancelText) as {
            status?: { state?: string };
            error?: { status?: string; message?: string };
        };
        const cancelled = await newestEvent(root, 'a2a.task.cancelled');
        record(rows, {
            step: 'a2a-cancel-run',
            requirement: 'R2 / F6',
            command: `POST /a2a/members/<member>/tasks/:cancel`,
            httpStatus: cancelRes.status,
            exitCode: null,
            passed:
                working === true &&
                cancelRes.status === 200 &&
                cancelBody?.status?.state === 'TASK_STATE_CANCELED' &&
                cancelled?.runStopped === true,
            expected: 'the run row reads running, cancel answers 200, state CANCELED and runStopped=true',
            evidence: `accepted=${String(working === true)} http ${cancelRes.status} state=${String(
                cancelBody?.status?.state,
            )} runStopped=${String(cancelled?.runStopped)} reason=${String(cancelBody?.error?.message ?? '').slice(
                0,
                120,
            )}`,
        });

        // The member loop survived: a SECOND request is claimed and runs (not a dead member).
        const second = await send('m-after-cancel');
        const secondBody = (await second.json().catch(() => null)) as { task?: { id?: string } } | null;
        const secondId = secondBody?.task?.id ?? '';
        // A queued request never reads WORKING: the projection only says that once the member has
        // claimed it and a live run row exists, which is exactly "the loop went on to the next task".
        const claimedAgain = await pollUntil(async () => {
            const res = await fetch(`${root}/a2a/members/${member}/tasks/${secondId}`, {
                headers: { Authorization: `Bearer ${A2A_TOKEN}` },
            });
            if (!res.ok) return undefined;
            const task = (await res.json()) as { status?: { state?: string } };
            return task.status?.state === 'TASK_STATE_WORKING' ? 'working' : undefined;
        }, 60_000);
        record(rows, {
            step: 'a2a-member-survives',
            requirement: 'R2 / F6',
            command: `POST message:send (second task) + GET /api/inbox/messages?member=<member> (in)`,

            httpStatus: second.status,
            exitCode: null,
            passed: loop.exitCode === null && second.status === 200 && claimedAgain !== undefined,
            expected: 'the member loop is still alive and claims the next request',
            evidence: `loopAlive=${String(loop.exitCode === null)} http ${second.status} claimed=${String(claimedAgain)}`,
        });

        // ── R2 / R7 — the status contract leaks no token ─────────────────────────────────
        const statusRes = await fetch(`${root}/api/integrations/status`, {
            headers: { 'x-forwarded-host': '127.0.0.1', 'x-forwarded-prefix': '/integrations-e2e' },
        });
        const statusText = await statusRes.text().catch(() => '');
        const status = JSON.parse(statusText === '' ? '{}' : statusText) as {
            mcp?: { enabled?: boolean; auth?: { envName?: string; tokenPresent?: boolean } };
            a2a?: { enabled?: boolean };
            gateway?: { served?: boolean };
        };
        record(rows, {
            step: 'integrations-status',
            requirement: 'R2 / R7',
            command: 'GET /api/integrations/status',
            httpStatus: statusRes.status,
            exitCode: null,
            passed:
                statusRes.status === 200 &&
                status.mcp?.enabled === true &&
                status.mcp.auth?.envName === MCP_AUTH_ENV &&
                status.mcp.auth?.tokenPresent === true &&
                status.a2a?.enabled === true &&
                !statusText.includes(MCP_TOKEN) &&
                !statusText.includes(A2A_TOKEN),
            expected: 'http 200, both surfaces enabled, the auth env NAME present and no token value',
            evidence: `http ${statusRes.status} mcp=${String(status.mcp?.enabled)} env=${String(
                status.mcp?.auth?.envName,
            )} tokenPresent=${String(status.mcp?.auth?.tokenPresent)} a2a=${String(
                status.a2a?.enabled,
            )} gatewayServed=${String(status.gateway?.served)}`,
        });
    } catch (error) {
        record(rows, {
            step: 'harness',
            requirement: '—',
            command: ARTIFACT,
            httpStatus: null,
            exitCode: 1,
            passed: false,
            expected: 'the harness completes every step',
            evidence: error instanceof Error ? error.message : String(error),
        });
    } finally {
        loop?.kill();
        serve?.kill();
        if (!keep) rmSync(scratch, { recursive: true, force: true });
    }

    // Self-check before writing: a receipt must never carry a token, even after redaction failed.
    const leaked = rows.some((row) => row.evidence.includes(MCP_TOKEN) || row.evidence.includes(A2A_TOKEN));
    if (leaked) {
        record(rows, {
            step: 'receipt-token-scan',
            requirement: 'R2 / R7',
            command: 'receipt scan',
            httpStatus: null,
            exitCode: 1,
            passed: false,
            expected: 'no token value in any row',
            evidence: 'a token value reached the evidence',
        });
    }

    const failed = rows.filter((row) => row.status === 'failed').length;
    const receipt = {
        artifact: ARTIFACT,
        generatedAt: new Date().toISOString(),
        context: { port, scratch: keep ? scratch : '(removed)', member },
        steps: rows,
        passed: rows.filter((row) => row.status === 'passed').length,
        failed,
        verdict: failed === 0 ? 'PASS' : 'FAIL',
    };
    mkdirSync(join(REPO_ROOT, 'docs/reports'), { recursive: true });
    writeFileSync(RECEIPT, `${JSON.stringify(receipt, null, 4)}\n`);

    console.log(`integrations-e2e receipt: ${relative(REPO_ROOT, RECEIPT)}`);
    for (const row of rows) {
        console.log(
            `  ${row.status === 'passed' ? 'ok  ' : 'FAIL'} ${row.step} [${row.requirement}]: ${row.evidence.slice(0, 160)}`,
        );
    }
    if (failed > 0) {
        console.error(
            `integrations-e2e: ${failed} step(s) failed: ${rows
                .filter((row) => row.status === 'failed')
                .map((row) => row.step)
                .join(', ')}`,
        );
        return 1;
    }
    return 0;
}

if (import.meta.main) {
    process.exit(await runIntegrationsE2e(process.argv.slice(2)));
}
