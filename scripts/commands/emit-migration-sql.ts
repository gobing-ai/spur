/**
 * Emit `packages/domain/src/migration-sql.generated.ts` from the released 0037 SQL (task 1312).
 *
 * The offline CLI bundle cannot read `drizzle/` at runtime, so migration SQL is embedded as a string.
 * This pilot makes the released `.sql` file the single authoring source for one mirror (0037, chosen
 * by the 1311 ownership evidence) instead of a handwritten twin. Released `.sql` bytes never change.
 *
 * Repo-internal dev-script, NOT a new public `spur` noun/verb (ADR-051).
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url));

export const MIGRATION_SQL_SOURCE = join(REPO_ROOT, 'drizzle/0037_spur_cli_history_dimension_marts.sql');

export function migrationSqlTarget(repoRoot: string = REPO_ROOT): string {
    return join(repoRoot, 'packages/domain/src/migration-sql.generated.ts');
}

/** Module text for the given SQL: a template literal with `\`, backtick and `${` escaped. */
export function renderMigrationSqlModule(sql: string): string {
    const literal = sql.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
    return (
        '// Generated by scripts/commands/emit-migration-sql.ts from\n' +
        '// drizzle/0037_spur_cli_history_dimension_marts.sql — edit nothing here; the .sql is released history.\n' +
        '/** Migration 0037: dimension marts (task 0743); verbatim released SQL. */\n' +
        `export const HISTORY_DIMENSION_MARTS_SCHEMA_SQL = \`${literal}\`;\n`
    );
}

/** Write the module. Returns the target path plus whether the file changed on disk. */
export async function emitMigrationSql(
    target: string = migrationSqlTarget(),
): Promise<{ target: string; changed: boolean }> {
    const text = renderMigrationSqlModule(await readFile(MIGRATION_SQL_SOURCE, 'utf-8'));
    const existing = await readFile(target, 'utf-8').catch(() => undefined);
    if (existing === text) return { target, changed: false };
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, text, 'utf-8');
    return { target, changed: true };
}
